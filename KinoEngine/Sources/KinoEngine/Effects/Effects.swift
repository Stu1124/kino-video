// MARK: - Masks

public enum KMaskKind: String, Codable, CaseIterable, Sendable {
    case rectangle
    case circle
    case linear
    case split
    case freeform
    case custom // point-based polygon
}

public struct MaskSpec: Hashable, Codable, Sendable {
    public var id: UUID
    public var kind: KMaskKind
    /// Normalized center (0..1) in clip space.
    public var center: KVec2
    /// Normalized size (0..1 of clip bounds). For linear: distance from line to edge.
    public var size: KVec2
    public var rotation: Float
    public var feather: Float      // 0..1
    public var inverted: Bool
    /// For linear/split: line normal angle (degrees).
    public var lineAngle: Float
    /// For split: which side is visible (0/1).
    public var splitSide: Float
    /// freezeform polygon points (normalized, clip space). Empty when not used.
    public var points: [KVec2]

    public init(id: UUID = UUID(),
                kind: KMaskKind = .rectangle,
                center: KVec2 = KVec2(0.5, 0.5),
                size: KVec2 = KVec2(0.5, 0.5),
                rotation: Float = 0,
                feather: Float = 0.1,
                inverted: Bool = false,
                lineAngle: Float = 45,
                splitSide: Float = 0,
                points: [KVec2] = []) {
        self.id = id
        self.kind = kind
        self.center = center
        self.size = size
        self.rotation = rotation
        self.feather = feather
        self.inverted = inverted
        self.lineAngle = lineAngle
        self.splitSide = splitSide
        self.points = points
    }
}

// MARK: - Chroma key instance

/// RGB triplet used by chroma keying (Codable-safe, no tuples).
public struct KRGB: Hashable, Codable, Sendable {
    public var r: Float
    public var g: Float
    public var b: Float
    public init(r: Float, g: Float, b: Float) { self.r = r; self.g = g; self.b = b }
    public var colorHex: UInt32 {
        (UInt32(min(1, r) * 255) << 16) | (UInt32(min(1, g) * 255) << 8) | UInt32(min(1, b) * 255)
    }
    /// Normalized proximity vs another color (0..1).
    public func distance(to o: KRGB) -> Float {
        let dr = r - o.r, dg = g - o.g, db = b - o.b
        return min(1, sqrt(dr * dr + dg * dg + db * db) / 1.7320508)
    }
}

public struct ChromaKeySpec: Hashable, Codable, Sendable {
    public var keyColor: KRGB
    public var similarity: Float   // tolerance 0..1
    public var smoothness: Float   // edge cleanup 0..1
    public var spill: Float        // spill suppression 0..1
    public var edgeFeather: Float

    public init(keyColor: KRGB = KRGB(r: 0, g: 1, b: 0),
                similarity: Float = 0.2, smoothness: Float = 0.2,
                spill: Float = 0.3, edgeFeather: Float = 0.05) {
        self.keyColor = keyColor
        self.similarity = similarity
        self.smoothness = smoothness
        self.spill = spill
        self.edgeFeather = edgeFeather
    }

    public init(colorHex: UInt32, similarity: Float = 0.2, smoothness: Float = 0.2, spill: Float = 0.3, edgeFeather: Float = 0.05) {
        self.init(keyColor: KRGB(r: Float((colorHex >> 16) & 0xFF) / 255,
                                 g: Float((colorHex >> 8) & 0xFF) / 255,
                                 b: Float(colorHex & 0xFF) / 255),
                  similarity: similarity, smoothness: smoothness, spill: spill, edgeFeather: edgeFeather)
    }

    public static let `default` = ChromaKeySpec()
}
