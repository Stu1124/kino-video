import Foundation

// MARK: - Effect parameter model

public enum KParamType: String, Codable, Sendable {
    case float
    case int
    case color
    case bool
    case select
}

public struct ParamSpec: Hashable, Codable, Sendable {
    public var key: String
    public var name: String
    public var type: KParamType
    public var min: Float
    public var max: Float
    public var defaultValue: Float
    public var step: Float
    /// select options for type == .select (index range maps to options).
    public var options: [String]

    public init(key: String, name: String, type: KParamType, min: Float = 0, max: Float = 1,
                defaultValue: Float = 0, step: Float = 0.01, options: [String] = []) {
        self.key = key
        self.name = name
        self.type = type
        self.min = min
        self.max = max
        self.defaultValue = defaultValue
        self.step = step
        self.options = options
    }
}

/// Kinds of renderer implementations.
public enum KEffectImpl: String, Codable, Sendable {
    /// Core Image chain generated by the platform layer (CI*).
    case coreImage
    /// Custom Metal kernel (defined in app's shader library; requires high-priority usage).
    case metal
    /// Parameter-only tweaks (e.g. brightness knob reused across effects).
    case colorAdjust
    /// Interactive region (e.g. lens flare position) with animated overlays.
    case compositor
}

/// Declaration of an available effect (catalogue entry).
public struct EffectSpec: Hashable, Codable, Sendable {
    public var id: String
    public var name: String
    public var family: String
    public var impl: KEffectImpl
    public var params: [ParamSpec]
    /// True when the effect supports per-time animation (keyframes baked in store).
    public var animatable: Bool

    public init(id: String, name: String, family: String, impl: KEffectImpl, params: [ParamSpec], animatable: Bool = true) {
        self.id = id
        self.name = name
        self.family = family
        self.impl = impl
        self.params = params
        self.animatable = animatable
    }

    public func param(_ key: String) -> ParamSpec? { params.first { $0.key == key } }
}

/// A concrete instance of an effect with explicit parameter values.
