// MARK: - Filter presets (color lookup + adjustments)

/// Color adjustment parameters (values in normalized -1..1 ranges where sensible).
public struct ColorAdjust: Hashable, Codable, Sendable {
    public var exposure: Float     // -2..2 EV
    public var brightness: Float   // -1..1
    public var contrast: Float     // -1..1
    public var highlights: Float   // -1..1
    public var shadows: Float      // -1..1
    public var saturation: Float   // -1..1 (0 = none, -1 = desaturate, 1 = push)
    public var vibrance: Float     // -1..1
    public var temperature: Float  // -1..1 (blue → amber)
    public var tint: Float         // -1..1 (green → magenta)
    public var fade: Float         // 0..1
    public var sharpen: Float      // 0..1
    public var vignette: Float     // 0..1
    public var grain: Float        // 0..1
    /// HSL shift chained curves: hueShift -0.5..0.5 (skip; replaced by curves where practical)
    public var hueShift: Float     // -0.5..0.5 full-cycle

    public init(exposure: Float = 0, brightness: Float = 0, contrast: Float = 0,
                highlights: Float = 0, shadows: Float = 0, saturation: Float = 0,
                vibrance: Float = 0, temperature: Float = 0, tint: Float = 0,
                fade: Float = 0, sharpen: Float = 0, vignette: Float = 0,
                grain: Float = 0, hueShift: Float = 0) {
        self.exposure = exposure
        self.brightness = brightness
        self.contrast = contrast
        self.highlights = highlights
        self.shadows = shadows
        self.saturation = saturation
        self.vibrance = vibrance
        self.temperature = temperature
        self.tint = tint
        self.fade = fade
        self.sharpen = sharpen
        self.vignette = vignette
        self.grain = grain
        self.hueShift = hueShift
    }

    public static let neutral = ColorAdjust()

    public func mixed(_ other: ColorAdjust, _ t: Float) -> ColorAdjust {
        func mix(_ a: Float, _ b: Float) -> Float { a + (b - a) * t }
        return ColorAdjust(
            exposure: mix(exposure, other.exposure),
            brightness: mix(brightness, other.brightness),
            contrast: mix(contrast, other.contrast),
            highlights: mix(highlights, other.highlights),
            shadows: mix(shadows, other.shadows),
            saturation: mix(saturation, other.saturation),
            vibrance: mix(vibrance, other.vibrance),
            temperature: mix(temperature, other.temperature),
            tint: mix(tint, other.tint),
            fade: mix(fade, other.fade),
            sharpen: mix(sharpen, other.sharpen),
            vignette: mix(vignette, other.vignette),
            grain: mix(grain, other.grain),
            hueShift: mix(hueShift, other.hueShift))
    }

    public var isNeutral: Bool { self == .neutral }
}

public struct FilterInstance: Hashable, Codable, Sendable {
    /// Preset id from FilterPreset.catalogue or "kino.custom".
    public var presetID: String
